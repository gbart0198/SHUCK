keys_path = Path("/tmp/keys_code.txt")
if keys_path.exists():
    try:
        for key in keys_path.read_text(encoding="utf-8").split():
            S.setdefault(key, key.replace("_", " ").title())
    except OSError:
        pass
out_path = Path("i18n/en.csv")
try:
    with out_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, quoting=csv.QUOTE_ALL)
        writer.writerow(["keys", "en"])
        for key in sorted(S):
            writer.writerow([key, S[key]])
except OSError as exc:
    raise SystemExit(f"could not write {out_path}: {exc}") from exc
print("wrote", len(S), "keys")
